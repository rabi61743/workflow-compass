    def handle(self, *args, **options):
        created_count = 0
        existing_count = 0
        
        for template in self.TEMPLATES:
            obj, created = LetterTemplate.objects.get_or_create(
                name=template['name'],
                defaults={
                    'name_nepali': template['name_nepali'],
                    'category': template['category'],
                    'content': template['content'],
                    'is_active': True,
                }
            )
            
            if created:
                created_count += 1
                self.stdout.write(self.style.SUCCESS(f"  Created: {template['name']}"))
            else:
                existing_count += 1
        
        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS(
            f'Done! Created: {created_count}, Already existed: {existing_count}'
        ))
